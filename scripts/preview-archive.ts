import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { EpisodePipeline, newEpisodeState, setArchiveShot, STAGES } from "../packages/pipeline/src/index.ts";
import { searchArchives, importArchiveImage } from "../packages/pipeline/src/archive.ts";
import { archiveCredits } from "../packages/pipeline/src/archive-credits.ts";
import { rasterizeSvg } from "../packages/pipeline/src/reference.ts";
import { FsAssetStore } from "../packages/storage/src/index.ts";
import { InMemoryLedger, MediaGateway } from "../packages/media-gateway/src/index.ts";
import { renderStills } from "../packages/video/src/render.ts";

// A real, isolated archive workflow fixture. No model or generated-media calls.
const root = resolve(process.argv[2] ?? "out/archive-workflow");
await mkdir(root, { recursive: true });
const store = new FsAssetStore(join(root, ".data/assets"));
const ledger = new InMemoryLedger();
const pipeline = new EpisodePipeline({ store, ledger, gateway: new MediaGateway({ providers: [], store, ledger }), workDir: join(root, ".data/episodes"), log: console.log });
const results = await searchArchives("Apollo 11", { store });
const choice = results.items.find((i) => i.provider === "nasa" && /spacecraft|launch/i.test(i.title)) ?? results.items.find((i) => i.provider === "nasa");
if (!choice) throw new Error(`No NASA image found: ${JSON.stringify(results.errors)}`);
const image = await importArchiveImage(choice.id, { store });
const original = await rasterizeSvg('<svg width="1280" height="720" viewBox="0 0 1280 720"><rect width="1280" height="720" fill="#24344d"/><circle cx="640" cy="360" r="160" fill="#e7bc64"/></svg>');
await store.put("assets/archive-fixture-original.png", original.data);
const state = newEpisodeState({ topic: "Archive workflow verification", lang: "en", targetSec: 4, tier: "economy", aiClipRatio: 0, budgetUsd: 1, width: 1280, height: 720, fps: 12, autoApprove: true, motionMode: "still", music: false, short: false });
state.id = "archive-workflow-verification";
state.script = { scenes: [{ id: "s1", beatId: "b1", narration: "Apollo 11 spacecraft", visualIntent: "Real archive image", emotion: "neutral", location: "Archive" }] };
state.voice = {};
state.shots = [{ id: "shot", sceneId: "s1", kind: "still_motion", startMs: 0, endMs: 4000, description: "Apollo 11 spacecraft", imagePrompt: "", motionPrompt: "", camera: "static" }];
state.keyframes = { shot: { key: "assets/archive-fixture-original.png", mimeType: "image/png" } };
state.done = Object.fromEntries(STAGES.slice(0, STAGES.indexOf("timeline")).map((s) => [s, new Date().toISOString()]));
setArchiveShot(state, "shot", image);
await pipeline.save(state);
await pipeline.run(state.id, { only: "timeline" });
const finished = await pipeline.run(state.id, { only: "render" });
if (finished.render?.archiveSources?.[0]?.source.id !== image.source.id) throw new Error("Wrong source frozen into render");
const publicDir = join(root, ".data/episodes", state.id, "public");
const stills = await renderStills({ timeline: finished.timeline!, publicDir, outDir: root, frames: { archive: 12 } });
const register = JSON.parse(await readFile(finished.render.path.replace(/\.mp4$/, ".sources.json"), "utf8"));
if (register.images[0].originalSha256 !== image.originalSha256 || (await ledger.list()).length) throw new Error("Source identity or zero-generation-call verification failed");
await writeFile(join(root, "verification.json"), JSON.stringify({ episodeId: state.id, video: finished.render.path, stills, sources: register, credits: archiveCredits(finished), ledgerEntries: 0 }, null, 2));
console.log(`Verified archive render: ${finished.render.path}`);
