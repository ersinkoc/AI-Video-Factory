/**
 * Hazır stil paketleri. Her bölüm bir paketle çizilir: "auto"da ucuz bir ajan konuya göre seçer, kullanıcı formdan
 * elle de seçebilir, "custom" eski serbest sanat yönetmenidir. Paket sabit olduğu için aynı paketteki bölümler aynı
 * elden çıkmış görünür ve kütüphanedeki karakterler paketler arasında değil, paket içinde tekrar kullanılır.
 *
 * Kurallar (sanat yönetmeninin kurallarıyla aynı): marka ya da yaşayan sanatçı adı yok, çerçeve/kenar/sayfa düzeni
 * yok, görselde yazı yok. designNotes SVG tasarımcısına gider: şekil dili, gölgeleme, oranlar.
 */
export interface StylePack {
  id: string;
  craft?: StyleCraft;
  name: { tr: string; en: string };
  /** Konuya göre seçen ajan için: hangi içeriklere yakışır (İngilizce). */
  suits: string;
  artStyle: string;
  palette: string[];
  lighting: string;
  lensLanguage: string;
  promptPrefix: string;
  negativeRules: string[];
  lineStyle: LineStyle;
  /** Render'da sahnenin üstüne binen doku (core/texture.ts): paketleri palet dışında da ayırır. */
  texture: Texture;
  designNotes: string;
  /**
   * 3D görünümlü paketlerde karakterler koddan kurulan 3D figürdür (core/figure.ts), yüzeyi bu. SVG çizim yine yapılır
   * (kalite kapısı, figürün dayanağı, WebGL yedeği); mekân ve nesneler SVG kalır.
   */
  figure?: FigureSpec["finish"];
}

